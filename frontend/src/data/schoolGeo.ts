/** Case-insensitive lookup cache (built once on first use). */
let _lowerCache: Map<string, LatLng> | null = null

function getLowerCache(): Map<string, LatLng> {
  if (!_lowerCache) {
    _lowerCache = new Map(
      Object.entries(SCHOOL_COORDS).map(([k, v]) => [k.toLowerCase(), v]),
    )
  }
  return _lowerCache
}

/**
 * Get coordinates for a school by name (case-insensitive).
 *
 * @param schoolName - School name to look up
 * @returns [lat, lng] pair or undefined if not found
 */
export function getSchoolCoords(schoolName: string): LatLng | undefined {
  const direct = SCHOOL_COORDS[schoolName]
  if (direct) return direct

  return getLowerCache().get(schoolName.toLowerCase())
}
